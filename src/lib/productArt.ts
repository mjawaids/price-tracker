const FALLBACK = 'basket';

/** The picture for an item type id, or null when there's none (its parent's, if drawn). */
export function artForType(id: string | null | undefined): string | null {
  if (!id) return null;
  const own = TYPE_ART[id] ?? (ART[id] ? id : null);
  if (own) return own;
  const parent = ITEM_TYPE_BY_ID.get(id)?.parent;
  return parent ? artForType(parent) : null;
}

const byCategory = (category: string | null | undefined) => {
  const id = categoryId(category);
  return (id && CATEGORY_ART[id]) || FALLBACK;
};

const productCache = new Map<string, string>();
const itemCache = new Map<string, string>();

/**
 * A product's picture: its item type, else one read from its name when that fits its
 * category (as `resolve.ts` does), else its aisle's, else a basket.
 */
export function artForProduct(p: { name: string; category?: string | null; itemType?: string | null }): string {
  const key = `${p.itemType ?? ''}|${p.category ?? ''}|${p.name}`;
  const hit = productCache.get(key);
  if (hit) return hit;
  let art = artForType(p.itemType);
  if (!art && p.name) {
    const parsed = parseProductName(p.name, { categoryHint: categoryId(p.category) });
    if (parsed.typeConfident) art = artForType(parsed.itemType?.id);
  }
  const out = art ?? byCategory(p.category);
  productCache.set(key, out);
  return out;
}

/** A list item's picture, from what was typed ("pyaz", "2 milk"), else its aisle's. */
export function artForItem(name: string, category?: string | null): string {
  const key = `${category ?? ''}|${name}`;
  const hit = itemCache.get(key);
  if (hit) return hit;
  const match = name ? matchItemType(name, categoryId(category)) : null;
  // The list's aisle can disagree with the type's ("tissue" sits in Cleaning, a moved
  // "milk" in Pantry): what was typed still names the thing when it names one type only.
  const sure = match && (match.confident || new Set(findTypes(name).map((m) => m.type.id)).size === 1);
  const out = (sure ? artForType(match.type.id) : null) ?? byCategory(category);
  itemCache.set(key, out);
  return out;
}
